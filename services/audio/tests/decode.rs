//! Decode integration tests: every fixture must probe correctly and decode
//! to its expected duration/rate, with ffmpeg's gapless trim preserved.

mod common;

use cadence_audio::decode::{Decoder, FfmpegDecoder};
use common::{decode_all, fixtures_dir, longest_zero_run};

#[test]
fn probe_all_fixtures() {
    let dir = fixtures_dir();
    let d = FfmpegDecoder;
    let cases = [
        ("tone-440.flac", "flac", 44100, 3000),
        ("tone-880.wav", "pcm_s16le", 44100, 3000),
        ("tone-660.mp3", "mp3", 44100, 3000),
        ("tone-550.m4a", "alac", 44100, 3000),
        ("tone-330-24bit96k.flac", "flac", 96000, 2000),
        ("tagged.flac", "flac", 44100, 3000),
        ("gapless-a.flac", "flac", 44100, 3000),
        ("gapless-b.flac", "flac", 44100, 3000),
    ];
    for (file, codec, rate, dur_ms) in cases {
        let info = d.probe(&dir.join(file)).unwrap_or_else(|e| panic!("{file}: {e}"));
        assert_eq!(info.codec, codec, "{file} codec");
        assert_eq!(info.sample_rate_hz, rate, "{file} rate");
        assert!(
            (info.duration_ms as i64 - dur_ms).abs() <= 60,
            "{file} duration {} vs {dur_ms}",
            info.duration_ms
        );
    }
}

#[test]
fn decode_every_fixture() {
    let dir = fixtures_dir();
    let cases = [
        ("tone-440.flac", 44100u32, 3000u64),
        ("tone-880.wav", 44100, 3000),
        ("tone-660.mp3", 44100, 3000),
        ("tone-550.m4a", 44100, 3000),
        ("tone-330-24bit96k.flac", 96000, 2000),
        ("tagged.flac", 44100, 3000),
    ];
    for (file, rate, dur_ms) in cases {
        let path = dir.join(file);
        let (pcm, got_rate) = decode_all(&path, None)
            .unwrap_or_else(|e| panic!("{file}: {e}"));
        assert_eq!(got_rate, rate, "{file} rate");
        let expected = (dur_ms * rate as u64 / 1000) as usize; // mono frames
        let got = pcm.len();
        let tol = (rate as usize) / 10; // 100ms tolerance for codec edge effects
        assert!(
            (got as i64 - expected as i64).abs() <= tol as i64,
            "{file}: {got} samples vs ~{expected}"
        );
        // fixtures are generated by ffmpeg's sine filter (amplitude ~1/8)
        let peak = pcm.iter().fold(0f32, |a, s| a.max(s.abs()));
        assert!(peak > 0.05, "{file} peak {peak}");
    }
}

#[test]
fn mp3_gapless_trim_is_applied() {
    // LAME adds ~1105+576 samples of encoder delay/padding. ffmpeg honors
    // the metadata; raw samples must span ~3s not ~3.05s.
    let (pcm, rate) = decode_all(&fixtures_dir().join("tone-660.mp3"), None).unwrap();
    let frames = pcm.len();
    let expected = 44100 * 3;
    let over = frames as i64 - expected as i64;
    assert!(
        over < 3000,
        "mp3 decoded to {} frames, expected ~{} (encoder delay not trimmed?)",
        frames,
        expected
    );
    assert!(rate == 44100);
}

#[test]
fn gapless_pair_is_contiguous_when_concatenated() {
    // a+b decoded contiguously must contain no inserted silence and no
    // discontinuity larger than the sine's natural max slope.
    let dir = fixtures_dir();
    let (a, rate_a) = decode_all(&dir.join("gapless-a.flac"), None).unwrap();
    let (b, rate_b) = decode_all(&dir.join("gapless-b.flac"), None).unwrap();
    assert_eq!(rate_a, rate_b);
    let n = a.len();
    let mut cat = a.clone();
    cat.extend_from_slice(&b);

    // no zero run anywhere except possibly endpoints of each file
    assert!(
        longest_zero_run(&cat[100..cat.len() - 100]) <= 4,
        "inserted silence inside concatenated pair"
    );

    // boundary step vs. interior max step: a 440Hz sine at amplitude 1 has
    // max |Δ| ~ 0.063 per sample at 44.1kHz.
    let boundary_step = (cat[n] - cat[n - 1]).abs();
    let interior_max = (0..n - 2)
        .map(|i| (cat[i + 1] - cat[i]).abs())
        .fold(0f32, f32::max);
    assert!(
        boundary_step <= interior_max * 1.5 + 1e-4,
        "boundary step {boundary_step} vs interior {interior_max}"
    );
}

#[test]
fn hi_res_flac_decodes_24bit() {
    let d = FfmpegDecoder;
    let info = d
        .probe(&fixtures_dir().join("tone-330-24bit96k.flac"))
        .unwrap();
    assert_eq!(info.sample_rate_hz, 96000);
    assert_eq!(
        info.bit_depth,
        cadence_audio::decode::BitDepth::Int(24),
        "expected 24-bit depth, got {:?}",
        info.bit_depth
    );
}
